// Ported from FairyGUI-unity: Assets/Scripts/UI/UIPanel.cs
using System;
using System.Collections.Generic;
using Godot;

namespace FairyGUI
{
    /// <summary>
    ///
    /// </summary>
    public enum FitScreen
    {
        None,
        FitSize,
        FitWidthAndSetMiddle,
        FitHeightAndSetCenter
    }

    /// <summary>
    ///
    /// </summary>
    // [Godot] Was a MonoBehaviour ([ExecuteInEditMode], [AddComponentMenu]). Now a Node2D that embeds a FairyGUI
    // component in a normal 2D scene: the UI is drawn in this node's canvas (it moves with Camera2D) and follows
    // this node's transform, like Unity's RenderMode.WorldSpace. The component lives under an internal Container
    // whose node is a child of this node; the Container is registered with Stage.RegisterPanel so it is updated
    // every frame and takes part in hit testing. For a screen-space UI use GRoot (or put this node in a CanvasLayer).
    // No editor preview (not [Tool]).
    [GlobalClass]
    public partial class UIPanel : Node2D, EMRenderTarget
    {
        /// <summary>
        ///
        /// </summary>
        public Container container { get; private set; }

        /// <summary>
        ///
        /// </summary>
        [Export]
        public string packageName = "";

        /// <summary>
        ///
        /// </summary>
        [Export]
        public string componentName = "";

        /// <summary>
        ///
        /// </summary>
        [Export]
        public FitScreen fitScreen;

        /// <summary>
        ///
        /// </summary>
        // [Godot] Order among UIPanels for hit testing (higher = tested first). Draw order follows the Godot scene
        // tree / ZIndex; keep both consistent.
        [Export]
        public int sortingOrder;

        // [Godot] Package asset path as used by UIPackage.AddPackage, e.g. "res://UI/Basics".
        [Export]
        string packagePath = "";
        // [Godot] renderMode / renderCamera removed: the panel always renders in the canvas of this node.
        // [Godot] Unity's serialized position/scale/rotation (offset of the UI inside the panel). Renamed to
        // uiPosition/uiScale/uiRotation: Godot exposes every field as a script property, and these names would
        // shadow Node2D's position/scale/rotation. Not exported: use the Node2D transform in the inspector.
        Vector3 uiPosition;
        Vector3 uiScale = new Vector3(1, 1, 1);
        Vector3 uiRotation = new Vector3(0, 0, 0);
        // [Godot] fairyBatching removed: Godot batches canvas items itself.
        [Export]
        bool touchDisabled = false;
        Vector2 cachedUISize;
        [Export]
        HitTestMode hitTestMode = HitTestMode.Default;
        // [Godot] setNativeChildrenOrder removed: native child nodes draw in scene tree order.

        int screenSizeVer;
        Rect uiBounds; //Track bounds even when UI is not created, edit mode

        GComponent _ui;
        bool _created;

        // [Godot] OnEnable + Start. Called again after the node re-enters the tree (see _ExitTree).
        public override void _Ready()
        {
            if (this.container == null)
            {
                CreateContainer();

                if (!string.IsNullOrEmpty(packagePath) && UIPackage.GetByName(packageName) == null)
                    UIPackage.AddPackage(packagePath);
            }

            // [Godot] Unity put the container under the Stage in CreateContainer (SetSortingOrder). Here it becomes
            // a registered panel once the node is in the tree.
            Stage.inst.RegisterPanel(this.container);

            if (!_created)
                CreateUI_PlayMode();
        }

        // [Godot] OnDisable removed: it only served edit mode (EMRenderSupport.Remove).

        // [Godot] Update()
        public override void _Process(double delta)
        {
            if (screenSizeVer != StageCamera.screenSizeVer)
                HandleScreenSizeChanged();
        }

        // [Godot] OnDestroy. Runs whenever the node leaves the tree; the UI is rebuilt by _Ready if it comes back.
        public override void _ExitTree()
        {
            if (container != null)
            {
                if (_ui != null)
                {
                    _ui.Dispose();
                    _ui = null;
                }

                if (Stage.IsRegisteredPanel(container))
                    Stage.inst.UnregisterPanel(container);
                container.Dispose();
                container = null;
            }

            _created = false;
            RequestReady();
        }

        void CreateContainer()
        {
            // [Godot] new Container(this.gameObject) -> an internal Container whose node is a child of this node.
            // The edit-mode cleanup of "UI(AutoGenerated)" children is removed (no edit mode).
            this.container = new Container("UIPanel");
            this.AddChild(this.container.node);
            this.container.touchable = !touchDisabled;
            this.container._panelOrder = sortingOrder;
            if (!Engine.IsEditorHint())
            {
                SetSortingOrder(this.sortingOrder, true);
                if (this.hitTestMode == HitTestMode.Raycast)
                {
                    // [Godot] ColliderHitTest + BoxCollider -> RectHitTest covering the UI (see UpdateHitArea).
                    RectHitTest hitArea = new RectHitTest();
                    this.container.hitArea = hitArea;
                }

                // [Godot] setNativeChildrenOrder / CacheNativeChildrenRenderers removed (Renderer.sortingOrder).
            }
        }

        /// <summary>
        ///
        /// </summary>
        public GComponent ui
        {
            get
            {
                if (!_created && !Engine.IsEditorHint())
                {
                    // [Godot] Unity's OnEnable had created the container already; here `ui` may be read before _Ready.
                    if (this.container == null)
                        CreateContainer();

                    if (!string.IsNullOrEmpty(packagePath) && UIPackage.GetByName(packageName) == null)
                        UIPackage.AddPackage(packagePath);

                    CreateUI_PlayMode();
                }

                return _ui;
            }
        }

        /// <summary>
        ///
        /// </summary>
        public void CreateUI()
        {
            if (_ui != null)
            {
                _ui.Dispose();
                _ui = null;
            }

            CreateUI_PlayMode();
        }

        /// <summary>
        /// Change the sorting order of the panel in runtime.
        /// </summary>
        /// <param name="value">sorting order value</param>
        /// <param name="apply">false if you dont want the default sorting behavior. e.g. call Stage.SortWorldSpacePanelsByZOrder later.</param>
        public void SetSortingOrder(int value, bool apply)
        {
            this.sortingOrder = value;
            container._panelOrder = value;

            // [Godot] Before _Ready the container is not registered yet; RegisterPanel inserts it by _panelOrder.
            if (apply && Stage.IsRegisteredPanel(container))
                Stage.inst.ApplyPanelOrder(container);
        }

        /// <summary>
        ///
        /// </summary>
        /// <param name="value"></param>
        public void SetHitTestMode(HitTestMode value)
        {
            if (this.hitTestMode != value)
            {
                this.hitTestMode = value;
                // [Godot] BoxCollider + ColliderHitTest -> RectHitTest covering the UI.
                if (this.hitTestMode == HitTestMode.Raycast)
                {
                    RectHitTest hitArea = new RectHitTest();
                    this.container.hitArea = hitArea;
                    if (_ui != null)
                        UpdateHitArea();
                }
                else
                {
                    this.container.hitArea = null;
                }
            }
        }

        // [Godot] CacheNativeChildrenRenderers removed: Godot draws child nodes in scene tree order, there is no
        // Renderer.sortingOrder / renderQueue to adjust.

        void CreateUI_PlayMode()
        {
            _created = true;

            if (string.IsNullOrEmpty(packageName) || string.IsNullOrEmpty(componentName))
                return;

            _ui = (GComponent)UIPackage.CreateObject(packageName, componentName);
            if (_ui != null)
            {
                _ui.position = uiPosition;
                if (uiScale.X != 0 && uiScale.Y != 0)
                    _ui.scale = uiScale.ToV2();
                _ui.rotationX = uiRotation.X;
                _ui.rotationY = uiRotation.Y;
                _ui.rotation = uiRotation.Z;
                if (this.container.hitArea != null)
                {
                    UpdateHitArea();
                    _ui.onSizeChanged.Add(UpdateHitArea);
                    _ui.onPositionChanged.Add(UpdateHitArea);
                }
                this.container.AddChildAt(_ui.displayObject, 0);

                HandleScreenSizeChanged();
            }
            else
                GD.PushError("Create " + packageName + "/" + componentName + " failed!");
        }

        void UpdateHitArea()
        {
            // [Godot] Unity sized a BoxCollider (y up); the RectHitTest rect is in the container's local space (y down).
            RectHitTest hitArea = this.container.hitArea as RectHitTest;
            if (hitArea != null && _ui != null)
            {
                hitArea.rect = new Rect(_ui.xMin, _ui.yMin, _ui.width, _ui.height);
            }
        }

        void CreateUI_EditMode()
        {
            if (!EMRenderSupport.packageListReady || UIPackage.GetByName(packageName) == null)
                return;

            // [Godot] DisplayObject.hideFlags / gameObject.hideFlags / gameObjectName removed (Unity editor only).
            GObject obj = UIPackage.CreateObject(packageName, componentName);
            if (obj != null && !(obj is GComponent))
            {
                obj.Dispose();
                GD.PushWarning("Not a GComponnet: " + packageName + "/" + componentName);
                return;
            }
            _ui = (GComponent)obj;

            if (_ui != null)
            {
                _ui.position = uiPosition;
                if (uiScale.X != 0 && uiScale.Y != 0)
                    _ui.scale = uiScale.ToV2();
                _ui.rotationX = uiRotation.X;
                _ui.rotationY = uiRotation.Y;
                _ui.rotation = uiRotation.Z;
                this.container.AddChildAt(_ui.displayObject, 0);

                cachedUISize = _ui.size;
                uiBounds.size = cachedUISize;
                HandleScreenSizeChanged();
            }
        }

        void HandleScreenSizeChanged()
        {
            // [Godot] DisplayObject.hideFlags (edit mode) removed.

            screenSizeVer = StageCamera.screenSizeVer;

            // [Godot] Screen.width/height -> Stage.inst.stageWidth/stageHeight. Multi-display handling and the
            // ScreenSpace scaling of the container (StageCamera.unitsPerPixel * scaleFactor) are removed: the panel
            // always behaves like Unity's RenderMode.WorldSpace, whose container is not scaled either.
            int width = Stage.inst.stageWidth;
            int height = Stage.inst.stageHeight;

            width = UMath.CeilToInt(width / UIContentScaler.scaleFactor);
            height = UMath.CeilToInt(height / UIContentScaler.scaleFactor);
            if (_ui != null)
            {
                switch (fitScreen)
                {
                    case FitScreen.FitSize:
                        _ui.SetSize(width, height);
                        _ui.SetXY(0, 0, true);
                        break;

                    case FitScreen.FitWidthAndSetMiddle:
                        _ui.SetSize(width, _ui.sourceHeight);
                        _ui.SetXY(0, (int)((height - _ui.sourceHeight) / 2), true);
                        break;

                    case FitScreen.FitHeightAndSetCenter:
                        _ui.SetSize(_ui.sourceWidth, height);
                        _ui.SetXY((int)((width - _ui.sourceWidth) / 2), 0, true);
                        break;
                }

                UpdateHitArea();
            }
            else
            {
                switch (fitScreen)
                {
                    case FitScreen.FitSize:
                        uiBounds.position = new Vector2(0, 0);
                        uiBounds.size = new Vector2(width, height);
                        break;

                    case FitScreen.FitWidthAndSetMiddle:
                        uiBounds.position = new Vector2(0, (int)((height - cachedUISize.Y) / 2));
                        uiBounds.size = new Vector2(width, cachedUISize.Y);
                        break;

                    case FitScreen.FitHeightAndSetCenter:
                        uiBounds.position = new Vector2((int)((width - cachedUISize.X) / 2), 0);
                        uiBounds.size = new Vector2(cachedUISize.X, height);
                        break;
                }
            }
        }

        #region edit mode functions

        // [Godot] OnUpdateSource(object[]) removed: it was invoked by the Unity inspector (SendMessage).

        public void ApplyModifiedProperties(bool sortingOrderChanged, bool fitScreenChanged)
        {
            if (container != null)
            {
                // [Godot] renderMode / renderCamera / fairyBatching do not exist in the Godot UIPanel.
                if (sortingOrderChanged)
                {
                    container._panelOrder = sortingOrder;
                    if (!Engine.IsEditorHint())
                        SetSortingOrder(sortingOrder, true);
                    else
                        EMRenderSupport.orderChanged = true;
                }
            }

            if (_ui != null)
            {
                if (fitScreen == FitScreen.None)
                    _ui.position = uiPosition;
                if (uiScale.X != 0 && uiScale.Y != 0)
                    _ui.scale = uiScale.ToV2();
                _ui.rotationX = uiRotation.X;
                _ui.rotationY = uiRotation.Y;
                _ui.rotation = uiRotation.Z;
            }
            if (fitScreen == FitScreen.None)
                uiBounds.position = uiPosition.ToV2();
            screenSizeVer = 0;//force HandleScreenSizeChanged be called

            if (fitScreenChanged && this.fitScreen == FitScreen.None)
            {
                if (_ui != null)
                    _ui.SetSize(_ui.sourceWidth, _ui.sourceHeight);
                uiBounds.size = cachedUISize;
            }
        }

        public void MoveUI(Vector3 delta)
        {
            if (fitScreen != FitScreen.None)
                return;

            this.uiPosition += delta;
            if (_ui != null)
                _ui.position = uiPosition;
            uiBounds.position = uiPosition.ToV2();
        }

        // [Godot] "World" position = canvas global position (z is always 0). Outside the tree the parent-relative
        // transform is used, as Godot cannot compute a global transform there.
        public Vector3 GetUIWorldPosition()
        {
            if (_ui != null)
            {
                Node2D n = _ui.displayObject.node;
                return (n.IsInsideTree() ? n.GlobalPosition : n.Position).ToV3();
            }
            else
            {
                Node2D n = this.container.node;
                Transform2D t = n.IsInsideTree() ? n.GlobalTransform : n.Transform;
                return (t * uiBounds.position).ToV3();
            }
        }

        // [Godot] OnDrawGizmos removed: Unity editor only.

        public int EM_sortingOrder
        {
            get { return sortingOrder; }
        }

        public void EM_BeforeUpdate()
        {
            if (container == null)
                CreateContainer();

            if (packageName != null && componentName != null && _ui == null)
                CreateUI_EditMode();

            if (screenSizeVer != StageCamera.screenSizeVer)
                HandleScreenSizeChanged();
        }

        public void EM_Update(UpdateContext context)
        {
            // [Godot] DisplayObject.hideFlags and setNativeChildrenOrder (Renderer.sortingOrder) removed.
            container.Update(context);
        }

        public void EM_Reload()
        {
            if (_ui != null)
            {
                _ui.Dispose();
                _ui = null;
            }
        }

        #endregion
    }
}
