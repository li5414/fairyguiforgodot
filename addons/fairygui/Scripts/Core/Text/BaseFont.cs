// Ported from FairyGUI-unity: Assets/Scripts/Core/Text/BaseFont.cs
using System;
using System.Collections.Generic;
using Godot;

namespace FairyGUI
{
    /// <summary>
    /// Base class for all kind of fonts.
    /// </summary>
    /// <remarks>
    /// [Godot] Two kinds of fonts exist:
    /// - Fonts that own their glyph texture (BitmapFont) write glyph quads into the VertexBuffer (DrawGlyph/DrawLine),
    ///   exactly as in Unity. NGraphics submits them.
    /// - Fonts rasterized by Godot (DynamicFont wraps Godot.Font) cannot write quads: Godot owns the glyph atlas.
    ///   They record TextField.GlyphRun entries into the list passed to StartDraw(graphics, glyphRuns), and TextField
    ///   draws them in OnNodeDraw with Godot.Font.DrawChar / DrawCharOutline / RenderingServer.CanvasItemAddRect.
    /// The layout API (SetFormat, GetGlyph, GetLineHeight...) is the same for both.
    /// </remarks>
    public class BaseFont
    {
        /// <summary>
        /// The name of this font object.
        /// </summary>
        public string name;

        /// <summary>
        /// The texture of this font object.
        /// </summary>
        /// <remarks>[Godot] DynamicFont uses NTexture.Empty: the glyph textures belong to Godot's TextServer.</remarks>
        public NTexture mainTexture;

        /// <summary>
        ///  Can this font be tinted? Will be true for dynamic font and fonts generated by BMFont.
        /// </summary>
        public bool canTint;

        /// <summary>
        /// If true, it will use extra vertices to enhance bold effect
        /// </summary>
        public bool customBold;

        /// <summary>
        /// If true, it will use extra vertices to enhance bold effect ONLY when it is in italic style.
        /// </summary>
        public bool customBoldAndItalic;

        /// <summary>
        /// If true, it will use extra vertices(4 direction) to enhance outline effect
        /// </summary>
        /// <remarks>[Godot] For DynamicFont it enables the DrawCharOutline outline and the shadow pass of TextField.</remarks>
        public bool customOutline;

        /// <summary>
        /// The shader for this font object.
        /// </summary>
        public string shader;

        /// <summary>
        /// Keep text crisp.
        /// </summary>
        public bool keepCrisp;

        /// <summary>
        ///
        /// </summary>
        public int version;

        protected internal static bool textRebuildFlag;

        protected const float SupScale = 0.58f;
        protected const float SupOffset = 0.33f;

        virtual public void SetFormat(TextFormat format, float fontSizeScale)
        {
        }

        virtual public void PrepareCharacters(string text, TextFormat format, float fontSizeScale)
        {
        }

        virtual public void Prepare(TextFormat format)
        {
        }

        virtual public bool BuildGraphics(NGraphics graphics)
        {
            return false;
        }

        virtual public void StartDraw(NGraphics graphics)
        {
        }

        /// <summary>
        /// [Godot] Called by TextField at the beginning of OnPopulateMesh. Fonts rasterized by Godot append the glyphs
        /// (and underline/strikethrough rectangles) drawn by DrawGlyph/DrawLine to glyphRuns instead of writing vertices.
        /// The default implementation ignores glyphRuns and calls StartDraw(graphics).
        /// </summary>
        /// <param name="graphics"></param>
        /// <param name="glyphRuns">Cleared by the caller. Positions are TextField local coordinates (y down).</param>
        virtual public void StartDraw(NGraphics graphics, List<TextField.GlyphRun> glyphRuns)
        {
            StartDraw(graphics);
        }

        virtual public bool GetGlyph(char ch, out float width, out float height, out float baseline)
        {
            width = 0;
            height = 0;
            baseline = 0;
            return false;
        }

        virtual public void DrawGlyph(VertexBuffer vb, float x, float y2)
        {
        }

        virtual public void DrawLine(VertexBuffer vb, float x, float y, float width, int fontSize, int type)
        {
        }

        virtual public bool HasCharacter(char ch)
        {
            return false;
        }

        virtual public int GetLineHeight(int size)
        {
            return 0;
        }

        virtual public void Dispose()
        {
        }
    }
}
